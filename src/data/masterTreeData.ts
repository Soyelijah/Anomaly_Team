export interface MasterSkillNode {
  id: string;
  skillId?: number; // Official Mu Online Season 6 Skill ID
  name: string;
  branch: 'defense' | 'mastery' | 'attack';
  row: number; // 1 to 5
  column: number; // 1 to 4
  maxPoints: number;
  icon: string;
  description: string;
  bonusPerPoint: string;
  currentPoints?: number;
  requiredParentId?: string;
}

export interface ClassMasterTree {
  classKey: string; // DW, DL, MG, FE, RF, BK, SU
  className: string;
  thirdClassName: string;
  baseMaxTreePoints: number; // 150 cap on Smash MU
  branches: {
    defense: {
      name: string;
      description: string;
      icon: string;
      skills: MasterSkillNode[];
    };
    mastery: {
      name: string;
      description: string;
      icon: string;
      skills: MasterSkillNode[];
    };
    attack: {
      name: string;
      description: string;
      icon: string;
      skills: MasterSkillNode[];
    };
  };
}

export interface RecommendedBuild {
  id: string;
  name: string;
  purpose: 'siege' | 'boss' | 'farm';
  badge: string;
  description: string;
  tacticalReason: string;
  statDistribution: {
    strength: number; // percentage of free points
    agility: number;
    vitality: number;
    energy: number;
    leadership?: number; // for DL
  };
  recommendedMasterFocus: string[];
  keyBreakpointNote: string;
}

export interface ClassBuildGuide {
  classKey: string;
  className: string;
  thirdClassName?: string;
  agilityBreakpoints: {
    safeRanges: string;
    bugRanges: string;
    explanation: string;
  };
  builds: RecommendedBuild[];
}

